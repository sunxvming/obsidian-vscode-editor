import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from 'fs';


const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;


let renamePlugin = {
	name: 'example',
	setup(build) {
		build.onEnd(result => {
			// fs.renameSync('main.css', 'styles.css');
			const mystyleData = fs.readFileSync('mystyles.css', 'utf8');
			const mainData = fs.readFileSync('main.css', 'utf8');
			const combinedData = mystyleData + '\n' + mainData;
			fs.writeFileSync('styles.css', combinedData, 'utf8');
			console.log('styles.css create success.');
		})
	},
}

const copyToDistPlugin = {
	name: 'copy-to-dist',
	setup(build) {
		build.onEnd(() => {
			fs.mkdirSync('dist', { recursive: true });
			for (const f of ['main.js', 'manifest.json', 'styles.css']) {
				if (fs.existsSync(f)) fs.copyFileSync(f, 'dist/' + f);
			}
			// tree-sitter WASM runtime + grammars, loaded at runtime by absolute path
			// (kept out of the esbuild bundle on purpose)
			const wasmFiles = [
				'node_modules/web-tree-sitter/web-tree-sitter.wasm',
				'node_modules/tree-sitter-c-sharp/tree-sitter-c_sharp.wasm',
				'node_modules/tree-sitter-rust/tree-sitter-rust.wasm',
			];
			for (const f of wasmFiles) {
				if (fs.existsSync(f)) fs.copyFileSync(f, 'dist/' + f.split('/').pop());
			}
			console.log('copied build output to dist/.');
		});
	},
}

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	// indicate how to load files with ttf extension, which is not supported by default
	// 'file':This loader will copy the file to the output directory, but this cont not load by obsidian 
	// 'base64': embed it into the bundle as a string using Base64 encoding	
	loader: {   
		'.ttf': 'base64', 
	},	
	plugins: [renamePlugin, copyToDistPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
